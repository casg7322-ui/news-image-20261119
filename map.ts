export interface MapDot {
  n: number;
  lon: number;
  lat: number;
  // Optional pixel offset (to separate overlapping dots).
  dx?: number;
  dy?: number;
}

export function drawMap(
  cv: Canvas,
  x: number,
  y: number,
  w: number,
  h: number,
  dots: MapDot[],
): void {
  const sea: RGB = hex("#1e3a5f");
  const land: RGB = hex("#d9c48a");
  cv.fillRect(x, y, w, h, sea);
  // Equirectangular: lon -180..180 -> x; lat 72..-55 -> y (mild vertical stretch).
  const sx = w / 360;
  const sy = (h / 127) * 1.0;
  const top = 72;
  const project = (lon: number, lat: number): [number, number] => [
    x + (lon + 180) * sx,
    y + (top - lat) * sy,
  ];
  for (const poly of LAND) {
    const pts = poly.map(([lo, la]) => project(lo, la));
    cv.fillPolygon(pts, land);
  }
  // Dots.
  const dotRed: RGB = hex("#dc2626");
  const white: RGB = hex("#ffffff");
  for (const d of dots) {
    const [px, py] = project(d.lon, d.lat);
    const cx = px + (d.dx ?? 0);
    const cy = py + (d.dy ?? 0);
    const label = String(d.n);
    const r = label.length > 1 ? 8.5 : 7.5;
    cv.fillCircle(cx, cy, r, dotRed);
    cv.circle(cx, cy, r, white, 1);
    const tw = label.length * 6 - 1;
    draw5x7(cv, label, cx - tw / 2, cy - 3.5, white, 1, true);
  }
}
